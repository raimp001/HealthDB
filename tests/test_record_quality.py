def test_an_import_stores_a_measured_score_not_a_constant(client, uploader):
    from api.models import ExtractedMedicalData

    assert upload(client, uploader,
                  {"resourceType": "Condition", "code": {"text": "AML"},
                   "onsetDateTime": "2020-05-04",
                   "clinicalStatus": {"text": "active"}},
                  {"resourceType": "Condition", "code": {"text": "CLL"}},
                  ).status_code == 200

    with client._session_factory() as db:
        scores = sorted(r.data_quality_score
                        for r in db.query(ExtractedMedicalData).all())
    assert len(set(scores)) > 1, f"every record scored the same: {scores}"
    assert 100.0 not in scores or scores.count(100.0) < len(scores)



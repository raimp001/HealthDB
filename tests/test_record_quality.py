def test_a_stale_stored_score_is_not_repeated_to_the_patient(client, uploader):
    """Rows stored before this still hold 100.0. No read path may repeat it."""
    from api.models import ExtractedMedicalData

    upload(client, uploader, {"resourceType": "Condition",
                              "code": {"text": "AML"}})
    with client._session_factory() as db:
        for row in db.query(ExtractedMedicalData).all():
            row.data_quality_score = 100.0
        db.commit()

    served = client.get("/api/patient/extracted-data", headers=uploader).json()
    assert all(r["data_quality_score"] < 100.0 for r in served), served



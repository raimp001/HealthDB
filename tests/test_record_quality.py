def test_gaps_are_named_the_way_a_person_would_name_them():
    gaps = describe_gaps(assess({"display": "AML"}, "diagnosis", "condition"))
    assert "year of diagnosis" in gaps
    assert "diagnosis_year" not in gaps


def test_an_unlabelled_field_is_left_out_rather_than_shown_raw():
    """Showing someone a raw field name is worse than showing them nothing."""
    gaps = describe_gaps({"missing": ["some_internal_key"]})
    assert gaps == []



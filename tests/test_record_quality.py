@pytest.fixture()
def admin(make_user):
    headers, _ = make_user("quality-admin@example.com", role="admin",
                           verified=True)
    return headers


def _falsely_verified(client):
    from api.models import ExtractedMedicalData, PatientProfile
    from datetime import datetime

    with client._session_factory() as db:
        patient_id = db.query(PatientProfile).first().id
        db.add(ExtractedMedicalData(
            patient_id=patient_id, connection_id="synthetic",
            data_category="diagnosis", data_type="condition",
            deidentified_data={"display": "AML"},
            data_quality_score=100.0, is_verified=True,
            verification_date=datetime.utcnow()))
        db.commit()


def test_the_audit_fails_on_a_record_claiming_verification(client, uploader):
    from api.self_audit import check_no_record_claims_verification

    upload(client, uploader, {"resourceType": "Condition",
                              "code": {"text": "AML"}})
    with client._session_factory() as db:
        assert check_no_record_claims_verification(db).passed

    _falsely_verified(client)
    with client._session_factory() as db:
        finding = check_no_record_claims_verification(db)
    assert not finding.passed
    assert finding.severity == "blocker"
    assert finding.count == 1


def test_the_repair_withdraws_the_claim_and_measures_the_score(client, uploader, admin):
    from api.models import ExtractedMedicalData
    from api.self_audit import check_no_record_claims_verification

    _falsely_verified(client)
    body = client.post("/api/admin/maintenance/unverified-claims",
                       headers=admin).json()
    assert body["applied"] is True
    assert body["records_corrected"] == 1

    with client._session_factory() as db:
        row = db.query(ExtractedMedicalData).filter(
            ExtractedMedicalData.is_verified.is_(False)).one()
        assert row.verification_date is None
        assert row.data_quality_score == 25.0
        assert check_no_record_claims_verification(db).passed


def test_the_repair_is_idempotent(client, uploader, admin):
    _falsely_verified(client)
    client.post("/api/admin/maintenance/unverified-claims", headers=admin)
    body = client.post("/api/admin/maintenance/unverified-claims",
                       headers=admin).json()
    assert body["applied"] is False
    assert body["records_corrected"] == 0


def test_a_non_admin_cannot_reach_the_repair(client, uploader):
    assert client.post("/api/admin/maintenance/unverified-claims",
                       headers=uploader).status_code in (401, 403)



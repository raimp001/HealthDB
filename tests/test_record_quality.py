"""A score has to measure something, and say what.

Every imported record used to be stored with data_quality_score = 100.0,
is_verified = True and a timestamp. Nothing had checked anything. The patient
saw "100% quality" beside the record they had just handed over — approval
generated by an assignment statement — and the researcher received a quality
column that was the same fabricated number on every row.

These tests hold two lines: the number is measured from the record, and
nothing claims the values are correct, because nothing here checks that.
"""
import pytest

from api.record_quality import (assess, describe_gaps, expected_fields, score)


DIAGNOSIS = {"display": "AML", "code": "C92.0", "diagnosis_year": 2020,
             "clinical_status": "active"}


# ---------------------------------------------------------------------------
# It measures the record in front of it
# ---------------------------------------------------------------------------

def test_a_full_record_scores_full():
    assert assess(DIAGNOSIS, "diagnosis", "condition")["score"] == 100.0


def test_a_thin_record_scores_lower_and_says_what_is_missing():
    thin = {"display": "AML"}
    result = assess(thin, "diagnosis", "condition")
    assert result["score"] == 25.0
    assert set(result["missing"]) == {"code", "diagnosis_year", "clinical_status"}


def test_the_score_is_never_the_same_number_for_every_record():
    """The defect this module exists to prevent."""
    scores = {
        score(DIAGNOSIS, "diagnosis", "condition"),
        score({"display": "AML"}, "diagnosis", "condition"),
        score({"age_band": "60-69", "sex": "female"}, "demographics", "patient"),
    }
    assert len(scores) == 3, scores


def test_the_basis_is_returned_with_the_number():
    """A number nobody can take apart is a rumour."""
    result = assess({"display": "AML"}, "diagnosis", "condition")
    assert "1 of 4" in result["basis"]
    assert result["expected"] == 4


# ---------------------------------------------------------------------------
# What counts as present
# ---------------------------------------------------------------------------

def test_a_result_of_zero_is_a_result():
    """Treating falsiness as absence is how real values get scored as gaps."""
    full = {"test": "Blast count", "code": "L1", "value": 0,
            "unit": "%", "year": 2021}
    assert assess(full, "lab_results", "blast")["score"] == 100.0


def test_false_is_a_recorded_value():
    recorded = {"vital_status": "Alive", "death_year": False}
    assert "death_year" in assess(recorded, "outcome", "vital_status")["present"]


@pytest.mark.parametrize("empty", [None, "", "   ", [], {}])
def test_an_empty_value_is_a_gap(empty):
    result = assess({"display": "AML", "code": empty, "diagnosis_year": 2020,
                     "clinical_status": "active"}, "diagnosis", "condition")
    assert "code" in result["missing"]


# ---------------------------------------------------------------------------
# What it refuses to claim
# ---------------------------------------------------------------------------

def test_an_unrecognised_record_kind_scores_none_not_zero():
    """Zero would claim a measurement was taken and came back empty."""
    result = assess({"anything": 1}, "something_new", "unmapped")
    assert result["score"] is None
    assert "no completeness expectations" in result["basis"].lower()


def test_the_denominator_does_not_shrink_when_a_record_carries_less():
    """Terminology annotation adds keys only when a term maps.

    Deriving the expected set from the payload's own keys would give an
    unmapped diagnosis a smaller denominator and score it *higher* for
    carrying less.
    """
    mapped = dict(DIAGNOSIS, icd10_code="C92.0", coding_source="healthdb")
    unmapped = dict(DIAGNOSIS)
    assert (assess(mapped, "diagnosis", "condition")["expected"]
            == assess(unmapped, "diagnosis", "condition")["expected"])


def test_nothing_in_the_assessment_claims_the_values_are_correct():
    """Completeness is not accuracy, and must never read as it."""
    text = " ".join(str(v) for v in assess(DIAGNOSIS, "diagnosis", "condition").values())
    for word in ("verified", "validated", "confirmed", "accurate", "correct"):
        assert word not in text.lower(), f"assessment implies accuracy: {text}"


def test_an_unknown_type_falls_back_to_the_category():
    """Lab results arrive with the test name as the type; every one is a lab."""
    assert (expected_fields("lab_results", "Hemoglobin")
            == expected_fields("lab_results", "Anything Else"))
    assert expected_fields("lab_results", "Hemoglobin")


